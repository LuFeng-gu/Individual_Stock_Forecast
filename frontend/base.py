"""
Abstract base class for frontend modules.

The frontend is responsible for initial audio understanding:
- Takes a question and an audio file path
- Produces a caption/description of the audio content

This file defines the INTERFACE (contract). Concrete implementations
(like OpenAICompatibleFrontend) must satisfy this contract.
"""

from abc import ABC, abstractmethod

from core.schemas import FrontendOutput
from core.errors import FrontendError


class BaseFrontend(ABC):
    """
    Abstract base class for audio frontends.
    
    A frontend takes a question and audio path, and produces initial evidence.
    Concrete implementations might use:
    - Local audio-language models (e.g., Qwen2-Audio)
    - Remote API-based services (e.g., OpenAI, DashScope)
    """

    @property
    @abstractmethod
    def name(self) -> str:
        """Return the name of this frontend for logging and identification."""
        raise NotImplementedError

    @abstractmethod
    def run(
        self,
        question: str,
        audio_path: str,
        question_oriented_prompt: str | None = None,
    ) -> FrontendOutput:
        """
        Process audio with the given question and produce initial evidence.

        Args:
            question: The user's question about the audio
            audio_path: Path to the audio file
            question_oriented_prompt: Optional customized prompt generated by planner.
                If provided, the frontend should use this instead of the raw question
                to guide its analysis.

        Returns:
            FrontendOutput with question-guided caption

        Raises:
            FrontendError: If processing fails or input is invalid
        """
        raise NotImplementedError

    def generate_final_answer(
        self,
        question: str,
        audio_path: str,
        context: dict,
    ) -> str:
        """
        Generate the final answer using the frontend audio model.
        
        This is called at the end of the workflow. The frontend receives
        the original audio plus all accumulated evidence to produce
        the final answer.

        Args:
            question: The original user question
            audio_path: Path to the audio file
            context: Dictionary with evidence_summary, planner_trace, etc.

        Returns:
            The final answer string

        Raises:
            FrontendError: If generation fails
            NotImplementedError: If this frontend doesn't support final answer
        """
        raise NotImplementedError(
            f"Frontend {self.name} does not support final answer generation"
        )

    def validate_inputs(self, question: str, audio_path: str) -> None:
        """
        Validate inputs before processing.
        Called by subclasses at the start of run().

        Raises:
            FrontendError: If inputs are invalid
        """
        if not question or not question.strip():
            raise FrontendError(
                "Question must be a non-empty string",
                details={"question": question},
            )
        if not audio_path or not audio_path.strip():
            raise FrontendError(
                "Audio path must be a non-empty string",
                details={"audio_path": audio_path},
            )
